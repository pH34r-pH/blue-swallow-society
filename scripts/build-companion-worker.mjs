import { createRequire } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const require = createRequire(new URL('../api/package.json', import.meta.url));
const { build } = require('esbuild');
const output = new URL('../api/_private/companion/dataset-worker.js', import.meta.url);
const result = await build({ entryPoints: [fileURLToPath(new URL('../api/_private/companion/data/worker.mjs', import.meta.url))],
  bundle: true, platform: 'browser', format: 'iife', target: 'es2022', minify: true, legalComments: 'inline', write: false,
  banner: { js: '// Generated by scripts/build-companion-worker.mjs; edit data/*.mjs, then regenerate.' } });
const bytes = result.outputFiles[0].contents;
if (process.argv.includes('--check')) {
  if (!Buffer.from(bytes).equals(await readFile(output))) throw new Error('Regenerate companion worker using the pinned toolchain.');
} else await writeFile(output, bytes);
